function flattenKeys(obj, prefix = '') {
  const keys = [];
  for (const [k, v] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${k}` : k;
    if (v !== null && typeof v === 'object' && !Array.isArray(v)) {
      keys.push(...flattenKeys(v, path));
    } else if (Array.isArray(v)) {
      keys.push(path);
      v.forEach((item, i) => {
        if (typeof item === 'object') keys.push(...flattenKeys(item, `${path}.${i}`));
        else keys.push(`${path}.${i}`);
      });
    } else {
      keys.push(path);
    }
  }
  return keys;
}

function deepEqualStructure(a, b, path = '') {
  const aKeys = Object.keys(a).sort();
  const bKeys = Object.keys(b).sort();
  if (JSON.stringify(aKeys) !== JSON.stringify(bKeys)) {
    const missingInB = aKeys.filter((k) => !bKeys.includes(k));
    const missingInA = bKeys.filter((k) => !aKeys.includes(k));
    return { ok: false, path, missingInB, missingInA };
  }
  for (const key of aKeys) {
    const nextPath = path ? `${path}.${key}` : key;
    const av = a[key];
    const bv = b[key];
    if (Array.isArray(av)) {
      if (!Array.isArray(bv) || av.length !== bv.length) return { ok: false, path: nextPath };
      continue;
    }
    if (av !== null && typeof av === 'object') {
      if (bv === null || typeof bv !== 'object') return { ok: false, path: nextPath };
      const result = deepEqualStructure(av, bv, nextPath);
      if (!result.ok) return result;
    }
  }
  return { ok: true };
}

